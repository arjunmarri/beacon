import Darwin
import Foundation

public struct NginxHealthResponse: Codable, Sendable {
    public let ok: Bool
    public let engine: String?
    public let port: Int?
    public let routes: Int?
}

/// Generates strictly sanitized, user-space `nginx.conf` files for BeaconMac's
/// inbuilt NGINX reverse proxy, probes the `/_beacon/nginx-health` endpoint,
/// and discovers the Mac's active LAN IPv4 address when LAN exposure is enabled.
public final class NginxProxyService: Sendable {
    public let configDirectoryURL: URL
    public let configFileURL: URL
    public let runtimeDirPath: String

    public init(dataDirectoryURL: URL) {
        self.configDirectoryURL = dataDirectoryURL.appendingPathComponent("nginx", isDirectory: true)
        self.configFileURL = configDirectoryURL.appendingPathComponent("nginx.conf")
        self.runtimeDirPath = "\(NSHomeDirectory())/beaconmac/nginx"
    }

    // MARK: - Strict Input Sanitization (Zero Config Injection)

    public static func sanitizePathPrefix(_ raw: String, fallbackName: String = "app") -> String {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "/-_"))
        var cleaned = ""
        for scalar in trimmed.unicodeScalars where allowed.contains(scalar) {
            cleaned.unicodeScalars.append(scalar)
        }
        while cleaned.contains("//") {
            cleaned = cleaned.replacingOccurrences(of: "//", with: "/")
        }
        cleaned = cleaned.trimmingCharacters(in: CharacterSet(charactersIn: "/"))
        if cleaned.isEmpty {
            let slug = BuiltInNodeServerService.makeSlug(from: fallbackName, existingSlugs: [])
            return "/\(slug)"
        }
        return "/\(cleaned)"
    }

    public static func sanitizeServerName(_ raw: String) -> String {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !trimmed.isEmpty else { return "" }
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: ".-"))
        var cleaned = ""
        for scalar in trimmed.unicodeScalars where allowed.contains(scalar) {
            cleaned.unicodeScalars.append(scalar)
        }
        cleaned = cleaned.trimmingCharacters(in: CharacterSet(charactersIn: ".-"))
        return cleaned.count <= 120 ? cleaned : String(cleaned.prefix(120))
    }

    public static func sanitizeTargetHost(_ raw: String) -> String {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if trimmed.isEmpty || trimmed == "localhost" || trimmed == "127.0.0.1" {
            return "127.0.0.1"
        }
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: ".-"))
        let cleaned = String(trimmed.unicodeScalars.filter { allowed.contains($0) })
        return cleaned.isEmpty ? "127.0.0.1" : cleaned
    }

    public static func clampedPort(_ port: Int, fallback: Int = 8080) -> Int {
        (80...65535).contains(port) ? port : fallback
    }

    // MARK: - Config Generation

    public func generateConfigText(from config: NginxProxyConfig, includeStubStatus: Bool = true) -> String {
        let listenPort = Self.clampedPort(config.listenPort, fallback: 8080)
        let bindDirective = config.exposeOnLAN ? "\(listenPort)" : "127.0.0.1:\(listenPort)"
        let enabledRoutes = config.routes.filter(\.enabled)
        let activeRootRoute = enabledRoutes.first(where: { $0.id == config.activeRootRouteID })

        let escapedRuntimeDir = runtimeDirPath.replacingOccurrences(of: "\"", with: "")

        var lines: [String] = [
            "# Auto-generated by BeaconMac Inbuilt NGINX Reverse Proxy",
            "# Do not hand-edit — managed from BeaconMac Dashboard",
            "worker_processes auto;",
            "pid \"\(escapedRuntimeDir)/nginx.pid\";",
            "error_log \"\(escapedRuntimeDir)/error.log\" warn;",
            "",
            "events {",
            "    worker_connections 1024;",
            "}",
            "",
            "http {",
            "    default_type application/octet-stream;",
            "    sendfile on;",
            "    tcp_nopush on;",
            "    tcp_nodelay on;",
            "    keepalive_timeout 65;",
            "    client_max_body_size 100m;",
            "",
            "    access_log \"\(escapedRuntimeDir)/access.log\";",
            "    client_body_temp_path \"\(escapedRuntimeDir)/client_body\";",
            "    proxy_temp_path \"\(escapedRuntimeDir)/proxy_temp\";",
            "    fastcgi_temp_path \"\(escapedRuntimeDir)/fastcgi_temp\";",
            "    uwsgi_temp_path \"\(escapedRuntimeDir)/uwsgi_temp\";",
            "    scgi_temp_path \"\(escapedRuntimeDir)/scgi_temp\";",
            "",
            "    map $http_upgrade $connection_upgrade {",
            "        default upgrade;",
            "        '' close;",
            "    }",
            ""
        ]

        // Default server block (handles localhost:<port>, 127.0.0.1:<port>, LAN IP:<port>, and path-based routes)
        lines.append("    server {")
        lines.append("        listen \(bindDirective) default_server;")
        lines.append("        server_name localhost 127.0.0.1 _;")
        lines.append("")
        // BeaconMac internal health probe
        lines.append("        # BeaconMac internal health probe")
        lines.append("        location = /_beacon/nginx-health {")
        lines.append("            access_log off;")
        lines.append("            default_type application/json;")
        lines.append("            return 200 '{\"ok\":true,\"engine\":\"nginx\",\"port\":\(listenPort),\"routes\":\(enabledRoutes.count)}';")
        lines.append("        }")
        lines.append("")
        if includeStubStatus {
            lines.append("        # BeaconMac real-time connection stats (loopback only)")
            lines.append("        location = /_beacon/nginx-status {")
            lines.append("            stub_status;")
            lines.append("            access_log off;")
            lines.append("            allow 127.0.0.1;")
            lines.append("            allow ::1;")
            lines.append("            deny all;")
            lines.append("        }")
            lines.append("")
        }

        // Path-based locations for all enabled routes
        var emittedPrefixes: Set<String> = []
        for route in enabledRoutes {
            let prefix = Self.sanitizePathPrefix(route.pathPrefix, fallbackName: route.name)
            guard prefix != "/", !emittedPrefixes.contains(prefix) else { continue }
            emittedPrefixes.insert(prefix)

            let host = Self.sanitizeTargetHost(route.targetHost)
            let port = max(1, min(65535, route.targetPort))
            let proxyTarget = route.stripPrefix ? "http://\(host):\(port)/" : "http://\(host):\(port)"

            lines.append("        # Route: \(route.name.replacingOccurrences(of: "\n", with: " "))")
            lines.append("        location = \(prefix) {")
            lines.append("            return 301 $scheme://$http_host\(prefix)/;")
            lines.append("        }")
            lines.append("        location ^~ \(prefix)/ {")
            lines.append("            proxy_pass \(proxyTarget);")
            lines.append("            proxy_http_version 1.1;")
            lines.append("            proxy_set_header Host $http_host;")
            lines.append("            proxy_set_header X-Real-IP $remote_addr;")
            lines.append("            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
            lines.append("            proxy_set_header X-Forwarded-Proto $scheme;")
            lines.append("            proxy_set_header X-Forwarded-Prefix \(prefix);")
            if route.webSocketsEnabled {
                lines.append("            proxy_set_header Upgrade $http_upgrade;")
                lines.append("            proxy_set_header Connection $connection_upgrade;")
            }
            lines.append("            proxy_buffering off;")
            lines.append("            proxy_read_timeout 300s;")
            lines.append("        }")
            lines.append("")
        }

        // Root ("/") behavior: either proxy the active root route or return a JSON route directory
        if let rootRoute = activeRootRoute {
            let host = Self.sanitizeTargetHost(rootRoute.targetHost)
            let port = max(1, min(65535, rootRoute.targetPort))
            lines.append("        # Active Root Route: \(rootRoute.name.replacingOccurrences(of: "\n", with: " "))")
            lines.append("        location / {")
            lines.append("            proxy_pass http://\(host):\(port);")
            lines.append("            proxy_http_version 1.1;")
            lines.append("            proxy_set_header Host $http_host;")
            lines.append("            proxy_set_header X-Real-IP $remote_addr;")
            lines.append("            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
            lines.append("            proxy_set_header X-Forwarded-Proto $scheme;")
            if rootRoute.webSocketsEnabled {
                lines.append("            proxy_set_header Upgrade $http_upgrade;")
                lines.append("            proxy_set_header Connection $connection_upgrade;")
            }
            lines.append("            proxy_buffering off;")
            lines.append("            proxy_read_timeout 300s;")
            lines.append("        }")
        } else {
            let routeListHTML = enabledRoutes.map { route -> String in
                let prefix = Self.sanitizePathPrefix(route.pathPrefix, fallbackName: route.name)
                let safeName = route.name
                    .replacingOccurrences(of: "&", with: "&amp;")
                    .replacingOccurrences(of: "<", with: "&lt;")
                    .replacingOccurrences(of: ">", with: "&gt;")
                    .replacingOccurrences(of: "'", with: "")
                return "<li><a href=\"\(prefix)/\">\(safeName)</a> <code>\(prefix)/</code> &rarr; <code>\(Self.sanitizeTargetHost(route.targetHost)):\(route.targetPort)</code></li>"
            }.joined()
            let bodyHTML = enabledRoutes.isEmpty
                ? "<!doctype html><html><body style=\"font-family:-apple-system,sans-serif;padding:32px;background:#0b0f17;color:#e2e8f0\"><h2>BeaconMac Inbuilt NGINX Reverse Proxy</h2><p>NGINX is running on port \(listenPort). Add a local app route inside BeaconMac to expose it here.</p></body></html>"
                : "<!doctype html><html><body style=\"font-family:-apple-system,sans-serif;padding:32px;background:#0b0f17;color:#e2e8f0\"><h2>BeaconMac Inbuilt NGINX Reverse Proxy</h2><p>Active local proxy routes on port \(listenPort):</p><ul style=\"line-height:2\">\(routeListHTML)</ul></body></html>"
            lines.append("        location = / {")
            lines.append("            default_type text/html;")
            lines.append("            return 200 '\(bodyHTML)';")
            lines.append("        }")
        }

        lines.append("    }")

        // Virtual-host server blocks for routes with custom serverName (e.g. myapp.localhost)
        var emittedHosts: Set<String> = []
        for route in enabledRoutes {
            let serverName = Self.sanitizeServerName(route.serverName)
            guard !serverName.isEmpty,
                  serverName != "localhost",
                  serverName != "127.0.0.1",
                  !emittedHosts.contains(serverName) else { continue }
            emittedHosts.insert(serverName)

            let host = Self.sanitizeTargetHost(route.targetHost)
            let port = max(1, min(65535, route.targetPort))

            lines.append("")
            lines.append("    # Virtual Host: \(serverName) -> \(host):\(port)")
            lines.append("    server {")
            lines.append("        listen \(bindDirective);")
            lines.append("        server_name \(serverName);")
            lines.append("")
            lines.append("        location / {")
            lines.append("            proxy_pass http://\(host):\(port);")
            lines.append("            proxy_http_version 1.1;")
            lines.append("            proxy_set_header Host $http_host;")
            lines.append("            proxy_set_header X-Real-IP $remote_addr;")
            lines.append("            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
            lines.append("            proxy_set_header X-Forwarded-Proto $scheme;")
            if route.webSocketsEnabled {
                lines.append("            proxy_set_header Upgrade $http_upgrade;")
                lines.append("            proxy_set_header Connection $connection_upgrade;")
            }
            lines.append("            proxy_buffering off;")
            lines.append("            proxy_read_timeout 300s;")
            lines.append("        }")
            lines.append("    }")
        }

        lines.append("}")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    @discardableResult
    public func writeConfig(from config: NginxProxyConfig, includeStubStatus: Bool = true) -> String {
        let text = generateConfigText(from: config, includeStubStatus: includeStubStatus)
        try? FileManager.default.createDirectory(at: configDirectoryURL, withIntermediateDirectories: true)
        try? text.data(using: .utf8)?.write(to: configFileURL, options: .atomic)
        return text
    }

    // MARK: - Loopback Health & Real-Time Connection Stats Probes

    public func probeHealth(port: Int) async -> NginxHealthResponse? {
        await probeHealthWithLatency(port: port)?.health
    }

    public func probeHealthWithLatency(port: Int) async -> (health: NginxHealthResponse, latencyMs: Int)? {
        guard (80...65535).contains(port),
              let url = URL(string: "http://127.0.0.1:\(port)/_beacon/nginx-health") else {
            return nil
        }

        var request = URLRequest(url: url)
        request.httpMethod = "GET"
        request.timeoutInterval = 2.0
        request.cachePolicy = .reloadIgnoringLocalCacheData

        let start = CFAbsoluteTimeGetCurrent()
        do {
            let (data, response) = try await URLSession.shared.data(for: request)
            let latencyMs = max(1, Int((CFAbsoluteTimeGetCurrent() - start) * 1000.0))
            guard let http = response as? HTTPURLResponse, http.statusCode == 200,
                  let decoded = try? JSONDecoder().decode(NginxHealthResponse.self, from: data) else {
                return nil
            }
            return (decoded, latencyMs)
        } catch {
            return nil
        }
    }

    public func probeStubStatus(port: Int) async -> NginxStubStatusSnapshot? {
        guard (80...65535).contains(port),
              let url = URL(string: "http://127.0.0.1:\(port)/_beacon/nginx-status") else {
            return nil
        }

        var request = URLRequest(url: url)
        request.httpMethod = "GET"
        request.timeoutInterval = 2.0
        request.cachePolicy = .reloadIgnoringLocalCacheData

        do {
            let (data, response) = try await URLSession.shared.data(for: request)
            guard let http = response as? HTTPURLResponse, http.statusCode == 200,
                  let body = String(data: data, encoding: .utf8) else {
                return nil
            }
            return Self.parseStubStatus(body, at: Date())
        } catch {
            return nil
        }
    }

    /// Parses NGINX `ngx_http_stub_status_module` plaintext output:
    /// ```
    /// Active connections: 3
    /// server accepts handled requests
    ///  48 48 112
    /// Reading: 0 Writing: 1 Waiting: 2
    /// ```
    public static func parseStubStatus(_ text: String, at date: Date = Date()) -> NginxStubStatusSnapshot? {
        let lines = text
            .split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        guard lines.count >= 4 else { return nil }

        // Line 1: Active connections: <N>
        guard let activeStr = lines[0].split(separator: ":").last?.trimmingCharacters(in: .whitespaces),
              let active = Int(activeStr) else {
            return nil
        }

        // Line 3: <accepts> <handled> <requests>
        let counters = lines[2].split(whereSeparator: \.isWhitespace).compactMap { Int($0) }
        guard counters.count >= 3 else { return nil }

        // Line 4: Reading: <R> Writing: <W> Waiting: <Wt>
        let tokens = lines[3].split(whereSeparator: \.isWhitespace).map(String.init)
        func valueAfter(_ key: String) -> Int? {
            guard let idx = tokens.firstIndex(where: { $0.caseInsensitiveCompare(key) == .orderedSame }),
                  idx + 1 < tokens.count else { return nil }
            return Int(tokens[idx + 1])
        }

        let reading = valueAfter("Reading:") ?? 0
        let writing = valueAfter("Writing:") ?? 0
        let waiting = valueAfter("Waiting:") ?? 0

        return NginxStubStatusSnapshot(
            activeConnections: active,
            accepts: counters[0],
            handled: counters[1],
            requests: counters[2],
            reading: reading,
            writing: writing,
            waiting: waiting,
            capturedAt: date
        )
    }

    // MARK: - Local Network IPv4 Discovery

    public static func detectPrimaryLANIPv4() -> String? {
        var ifaddr: UnsafeMutablePointer<ifaddrs>?
        guard getifaddrs(&ifaddr) == 0, let firstAddr = ifaddr else { return nil }
        defer { freeifaddrs(ifaddr) }

        var fallbackIP: String?
        var ptr: UnsafeMutablePointer<ifaddrs>? = firstAddr
        while let current = ptr {
            let flags = Int32(current.pointee.ifa_flags)
            let isUp = (flags & IFF_UP) != 0
            let isRunning = (flags & IFF_RUNNING) != 0
            let isLoopback = (flags & IFF_LOOPBACK) != 0

            if isUp && isRunning && !isLoopback,
               let addr = current.pointee.ifa_addr,
               addr.pointee.sa_family == UInt8(AF_INET) {
                var hostname = [CChar](repeating: 0, count: Int(NI_MAXHOST))
                let res = getnameinfo(
                    addr,
                    socklen_t(addr.pointee.sa_len),
                    &hostname,
                    socklen_t(hostname.count),
                    nil,
                    0,
                    NI_NUMERICHOST
                )
                if res == 0 {
                    let ip = String(cString: hostname)
                    let ifName = current.pointee.ifa_name.map { String(cString: $0) } ?? ""
                    if ifName == "en0" || ifName == "en1" {
                        return ip
                    }
                    if fallbackIP == nil {
                        fallbackIP = ip
                    }
                }
            }
            ptr = current.pointee.ifa_next
        }
        return fallbackIP
    }
}
